class FakeVersionedStore:
    """Synthetic-only provider; no SDK or transport exists in this module."""
    def __init__(self, denied=False, corrupt=False, tls_verified=True,
                 encryption='AES256', versioning='Enabled'):
        self.denied = denied
        self.corrupt = corrupt
        self.tls_verified = tls_verified
        self.encryption = encryption
        self.versioning = versioning
        self.objects = {}

    def put(self, body):
        if self.denied:
            raise ValueError('simulated_permission_denied')
        key = sha(body)
        self.objects.setdefault(key, body)
        return key

    def get(self, version):
        body = self.objects[version]
        return body + b'corrupt' if self.corrupt else body


def simulate(schema=38, store=None, state=None, fault=None):
    """Resume JSON-compatible synthetic state; never accepts real backup bytes."""
    if schema not in SCHEMAS or fault not in (None, 'interrupt', 'table', 'ledger', 'sequence'):
        raise ValueError('unsupported_simulation')
    if store is None:
        store = FakeVersionedStore()
    if type(store) is not FakeVersionedStore:
        raise ValueError('synthetic_provider_required')
    if (store.tls_verified is not True or store.encryption != 'AES256'
            or store.versioning != 'Enabled'):
        raise ValueError('simulated_storage_security_unverified')
    body = ('SOCIALMEI SYNTHETIC ONLY schema' + str(schema)).encode()
    expected = sha(body)
    checkpoint = copy.deepcopy(state) if state else {'schema': schema, 'sha256': expected}
    if checkpoint.get('schema') != schema or checkpoint.get('sha256') != expected:
        raise ValueError('checkpoint_identity_mismatch')
    version = checkpoint.get('version') or store.put(body)
    checkpoint.update(version=version, complete=False, simulated=True)
    if fault == 'interrupt':
        return checkpoint
    readback = store.get(version)
    if len(readback) != len(body) or sha(readback) != expected:
        raise ValueError('simulated_readback_corrupt')
    spec = importlib.util.spec_from_file_location('copy_validate', Path(__file__).with_name('postgres-copy-validate.py'))
    validator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(validator)
    source = {'manifest_version': 1, 'large_objects': 0, 'structure': {},
              'tables': [{'name': 'synthetic', 'rows': 1, 'sha256': expected}],
              'migration_ledger': [{'schema': 'synthetic', 'versions': list(range(1, schema + 1))}],
              'sequences': [{'name': 'synthetic_id', 'last_value': 1, 'is_called': True}],
              'foreign_keys': [], 'effective_permissions': [], 'effective_sequence_permissions': [], 'valid': True}
    restored = copy.deepcopy(source)
    if fault == 'table':
        restored['tables'][0]['rows'] = 0
    elif fault == 'ledger':
        restored['migration_ledger'][0]['versions'].pop()
    elif fault == 'sequence':
        restored['sequences'][0]['is_called'] = False
    comparison = validator.compare(source, restored)
    if not comparison['equal']:
        raise ValueError('simulated_restore_mismatch')
    checkpoint.update(complete=True, comparison_equal=True,
                      real_backup_certified=False, production_updates=False)
    return checkpoint


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('plan', 'simulate'))
    parser.add_argument('--evidence', type=Path, help='Sanitized evidence JSON, never private configuration')
    parser.add_argument('--schema', type=int, choices=SCHEMAS, default=38)
    args = parser.parse_args(argv)
    try:
        if args.mode == 'plan':
            result = make_plan(json.loads(args.evidence.read_text()) if args.evidence else {})
        else:
            result = simulate(args.schema)
        print(json.dumps(result, indent=2))
        return 0
    except Exception:
        print(json.dumps({'complete': False, 'reason': 'offline_plan_or_simulation_failed'}))
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
